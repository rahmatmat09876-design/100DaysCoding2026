public class Day14 {
    public static void main(String[] args) {

        // Operator Aritmatika Penjumlahan (+) dan Pengurangan (-)
        int nilai1 = 75;
        int nilai2 = 25;
        int nilai3 = 10;

        System.out.println("Hasil penjumlahan : " + (nilai1 + nilai2));
        System.out.println("Hasil pengurangan : " + (nilai1 - nilai2));
        System.out.println("Hasil operasi gabungan : " + (nilai1 + nilai2 - nilai3));
    }
}
